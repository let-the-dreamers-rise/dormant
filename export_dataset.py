"""Emit the semantics as data, not as code.

The library is the reference implementation; the dataset is the deliverable.
An indexer or a wallet should not have to import Python to find out that
`SetAuthority` moves permanent control, or that a pump.fun `Sell` is bounded
by a slippage limit the trade is allowed not to reach.

The rows are GENERATED BY RUNNING THE LIBRARY, never hand-maintained beside
it. A dataset transcribed by hand from code drifts from that code the first
time somebody fixes a verdict and forgets the copy, and a stale semantics file
is worse than none -- it is wrong with the authority of a published artefact.

Two properties are derived rather than asserted, by analysing each operation
more than once and comparing:

    signer_sensitive   the verdict changes when the accounts that do not sign
                       become signers. This is the precondition the library
                       actually computes, surfaced as a queryable field.

    effect_is_template the statement changes with the instruction's payload,
                       so the text here is a shape with this row's example
                       values in it, not a constant.

    python export_dataset.py
"""

from __future__ import annotations

import json
import struct
import subprocess
from pathlib import Path

from dormant import semantics as S
from dormant.wire import Account, Instruction

OUT = Path("dataset/semantics.json")

KEYS = ["Sig1" + "1" * 40, "Sig2" + "2" * 40, "Acc3" + "3" * 40,
        "Acc4" + "4" * 40, "Acc5" + "5" * 40, "Acc6" + "6" * 40]


ALT_KEYS = ["Alt" + str(i) + str(i) * 41 for i in range(1, 7)]


def instruction(program: str, data: bytes, all_signers: bool = False,
                keys=None):
    accounts = [Account(k, all_signers or i < 2, True)
                for i, k in enumerate(keys or KEYS)]
    return Instruction(program=program, accounts=accounts, data=data)


def context(all_signers: bool = False):
    signers = frozenset(KEYS if all_signers else KEYS[:2])
    return S.Context(signers=signers, accounts=frozenset(KEYS))


def finding(program: str, data: bytes, all_signers: bool = False, keys=None):
    return S.analyse_instruction(
        instruction(program, data, all_signers, keys), context(all_signers))


# Enough trailing zeros that every operation's argument reads land inside the
# buffer. A short payload would make operations look truncated rather than
# modelled, which is a property of this fixture and not of the program.
PAD = b"\x00" * 48
ALT = b"\x07" * 48


def u32_tag(tag: int, pad: bytes) -> bytes:
    return struct.pack("<I", tag) + pad


def u8_tag(tag: int, pad: bytes) -> bytes:
    return bytes([tag]) + pad


def hex_tag(disc: str, pad: bytes) -> bytes:
    return bytes.fromhex(disc) + pad


PROGRAMS = [
    ("System Program", S.SYSTEM, "u32 little-endian at offset 0",
     S.SYSTEM_OPS, u32_tag, "native"),
    ("SPL Token", S.TOKEN, "u8 at offset 0", S.TOKEN_OPS, u8_tag, "native"),
    ("Token-2022", S.TOKEN22, "u8 at offset 0", S.TOKEN_OPS, u8_tag, "native"),
    ("BPF Loader Upgradeable", S.LOADER_UPGRADEABLE,
     "u32 little-endian at offset 0", S.LOADER_OPS, u32_tag, "native"),
    ("Stake Program", S.STAKE, "u32 little-endian at offset 0",
     S.STAKE_OPS, u32_tag, "native"),
    ("Vote Program", S.VOTE, "u32 little-endian at offset 0",
     S.VOTE_OPS, u32_tag, "native"),
    ("pump.fun AMM", S.PUMP_AMM, "8-byte Anchor discriminator at offset 0",
     dict({d: v[0] for d, v in S.PUMP_OPS.items()},
          **{S.ANCHOR_EVENT: "event"}), hex_tag, "reverse-engineered"),
]

# Programs whose whole surface is one behaviour rather than a tag table.
SINGLETONS = [
    ("Associated Token Account", S.ATA, b"", "native"),
    ("Memo", S.MEMO, b"note", "native"),
    ("Memo (legacy)", S.MEMO_LEGACY, b"note", "native"),
    ("Compute Budget", S.COMPUTE_BUDGET, b"\x02\x00\x00\x00\x00", "native"),
]


def row(program: str, tag, data: bytes, alt_data: bytes) -> dict:
    base = finding(program, data)
    as_signer = finding(program, data, all_signers=True)
    # Vary BOTH the payload and the accounts, so a statement that names an
    # account is flagged as a template too. Varying only the data would let
    # "authority over Sig1..1111" masquerade as a constant fact.
    varied = finding(program, alt_data, keys=ALT_KEYS)
    return {
        "tag": tag,
        "operation": base.operation,
        "verdict": base.verdict,
        "effect": base.statement,
        "effect_is_template": varied.statement != base.statement,
        "precondition": base.precondition,
        "precondition_evaluated": base.evaluated,
        "unconditional": base.unconditional,
        "signer_sensitive": as_signer.verdict != base.verdict,
    }


def build() -> dict:
    try:
        commit = subprocess.check_output(
            ["git", "rev-parse", "--short", "HEAD"],
            stderr=subprocess.DEVNULL).decode().strip()
    except Exception:
        commit = "unknown"

    programs = []
    for name, pid, encoding, ops, build_tag, source in PROGRAMS:
        rows = []
        for tag in sorted(ops, key=lambda t: (isinstance(t, str), t)):
            rows.append(row(pid, tag,
                            build_tag(tag, PAD), build_tag(tag, ALT)))
        programs.append({
            "program": pid, "name": name, "tag_encoding": encoding,
            "semantics_source": source, "operations": rows,
        })

    for name, pid, data, source in SINGLETONS:
        programs.append({
            "program": pid, "name": name, "tag_encoding": "none",
            "semantics_source": source,
            "operations": [row(pid, None, data, data + b"!")],
        })

    total_ops = sum(len(p["operations"]) for p in programs)
    return {
        "schema": "dormant.semantics/1",
        "license": "MIT",
        "generated_from_commit": commit,
        "generator": "export_dataset.py",
        "note": ("Generated by running the library, never hand-edited. "
                 "Verdicts: SAFE, NOTICE, CRITICAL, UNKNOWN. An operation "
                 "absent from this file is UNKNOWN, which is not a statement "
                 "that it is safe."),
        "counts": {"programs": len(programs), "operations": total_ops},
        "argument_layouts": {
            S.PUMP_AMM: {
                "note": ("Recovered from mainnet by measurement/discover.py "
                         "and tested against the ledger's own balance "
                         "deltas, not read from source."),
                "fields": [
                    {"offset": 0, "width": 8, "meaning": "discriminator"},
                    {"offset": 8, "width": 8, "meaning": "amount",
                     "evidence": "matched an observed balance delta in 96.6% "
                                 "of Buy (140/145) and 73.9% of Sell "
                                 "(156/211)"},
                    {"offset": 16, "width": 8, "meaning": "slippage bound",
                     "evidence": "matched an observed delta in only 4.1% and "
                                 "0.5% of the same samples -- a limit the "
                                 "trade is permitted not to reach"},
                ],
            },
        },
        "programs": programs,
    }


def main() -> int:
    data = build()
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print("wrote %s -- %d programs, %d operations"
          % (OUT, data["counts"]["programs"], data["counts"]["operations"]))
    unknown = sum(1 for p in data["programs"] for o in p["operations"]
                  if o["verdict"] == "UNKNOWN")
    sensitive = sum(1 for p in data["programs"] for o in p["operations"]
                    if o["signer_sensitive"])
    print("  %d operations are signer-sensitive (verdict depends on who signs)"
          % sensitive)
    print("  %d rows still UNKNOWN" % unknown)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
